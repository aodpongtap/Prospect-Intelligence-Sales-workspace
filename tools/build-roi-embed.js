// ฝังเครื่องคำนวณ ROI (roi-calculator/index.html) ไว้ในเว็บหลัก
// ใช้: node tools/build-roi-embed.js
// ผลลัพธ์: assets/roi-calculator-embed.js → window.__ROI_HTML__
// แก้สูตร/หน้าตาที่ roi-calculator/index.html แล้วรันสคริปต์นี้อีกครั้ง
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const SRC = path.join(ROOT, 'roi-calculator', 'index.html');
const OUT = path.join(ROOT, 'assets', 'roi-calculator-embed.js');

let html = fs.readFileSync(SRC, 'utf8');

// 1) บังคับโหมด embed (ซ่อน topbar ของเครื่องคำนวณ / พื้นหลังโปร่ง)
if (/<html[^>]*>/.test(html)) {
  html = html.replace(/<html([^>]*)>/, function (m, attrs) {
    if (/class=/.test(attrs)) return '<html' + attrs.replace(/class="([^"]*)"/, 'class="$1 embed"') + '>';
    return '<html' + attrs + ' class="embed">';
  });
}

// 2) กัน localStorage โยน error ในกรณี srcdoc มี opaque origin (file://)
const shim = '<script>try{window.localStorage.getItem("x");}catch(e){try{Object.defineProperty(window,"localStorage",{value:{getItem:function(){return null;},setItem:function(){},removeItem:function(){}}});}catch(_){}}</script>';
html = html.replace(/<head([^>]*)>/i, '<head$1>' + shim);

// 3) เขียนเป็น JS string (escape </script> เพื่อให้ฝังใน <script> ภายหลังได้)
//    ⚠️ ทุกครั้งที่รันไฟล์นี้ ให้ bump ?v= ของ <script src="assets/roi-calculator-embed.js?v=N"> ใน index.html ด้วย
//       ไม่อย่างนั้นเบราว์เซอร์จะใช้ไฟล์เก่าจาก cache
const js = '/* generated by tools/build-roi-embed.js — อย่าแก้ไฟล์นี้โดยตรง */\n'
  + 'window.__ROI_HTML__ = ' + JSON.stringify(html).replace(/<\/script/gi, '<\\/script') + ';\n';

fs.writeFileSync(OUT, js, 'utf8');
console.log('✔ assets/roi-calculator-embed.js (' + Math.round(js.length / 1024) + ' KB) จาก roi-calculator/index.html');
